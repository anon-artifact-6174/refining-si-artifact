#!/usr/bin/env python3
"""Report the throughput speedup of one isolation mode over another.

Both the client sweep (plot_benchmark.py) and the SmallBank sweep
(plot_sweep.py) want the same headline number for the paper: how much faster is
the treatment mode than the baseline at the point where the gap is largest.

The headline ratio is measured at a single, consistently chosen operating
point: the concurrency level x* at which the TREATMENT peaks.

  ratio at x*    treatment(x*) / baseline(x*), where x* = argmax treatment(x).
                 Both modes are read off the same x, so this is an apples-to-
                 apples comparison at the configuration we would actually
                 deploy the treatment at. This is the number to quote.

Two further ratios are reported for context only, since they answer different
questions and can disagree with the headline:

  independent    peak(treatment) / peak(baseline), each maximized separately.
                 Flattering to the treatment when the baseline peaks elsewhere,
                 because it compares the two modes at different x.

  max pointwise  max over x of treatment(x) / baseline(x). An upper bound; it
                 cherry-picks whichever x maximizes the gap.

Both numbers are also emitted as LaTeX macros (see `write_tex`) so the paper
can \input the generated file and never hard-code a speedup it might forget to
update after a re-run.
"""
import datetime
import os

# LaTeX command names may only contain letters, so numeric group labels
# ("0.25", "20") are spelled out digit by digit.
_DIGIT_WORDS = {
    "0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
    "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine",
    ".": "Point", "-": "Neg",
}


def tex_name(label):
    """Turn a group label into a letters-only LaTeX-safe fragment."""
    out = []
    for ch in str(label):
        if ch.isalpha():
            out.append(ch)
        elif ch in _DIGIT_WORDS:
            out.append(_DIGIT_WORDS[ch])
    return "".join(out) or "Group"


def _as_map(xs, ys):
    """{x: y}, keeping the max y if an x was measured more than once."""
    m = {}
    for x, y in zip(xs, ys):
        if x in m:
            m[x] = max(m[x], y)
        else:
            m[x] = y
    return m


def compare(base_xy, treat_xy):
    """Speedup stats for one group, or None if either series is unusable.

    base_xy / treat_xy are (xs, ys) pairs.
    """
    base = _as_map(*base_xy)
    treat = _as_map(*treat_xy)
    base_pos = {x: y for x, y in base.items() if y > 0}
    treat_pos = {x: y for x, y in treat.items() if y > 0}
    if not base_pos or not treat_pos:
        return None

    base_peak_x = max(base_pos, key=base_pos.get)
    treat_peak_x = max(treat_pos, key=treat_pos.get)
    base_peak = base_pos[base_peak_x]
    treat_peak = treat_pos[treat_peak_x]

    shared = sorted(set(base_pos) & set(treat))
    best_x = best_ratio = None
    for x in shared:
        r = treat[x] / base_pos[x]
        if best_ratio is None or r > best_ratio:
            best_ratio, best_x = r, x

    # Headline: both modes read off the treatment's peak concurrency.
    base_at_treat_peak = base_pos.get(treat_peak_x)
    ratio_at_treat_peak = (treat_peak / base_at_treat_peak
                           if base_at_treat_peak else None)

    return {
        "base_peak": base_peak,
        "base_peak_x": base_peak_x,
        "treat_peak": treat_peak,
        "treat_peak_x": treat_peak_x,
        "base_at_treat_peak": base_at_treat_peak,
        "ratio_at_treat_peak": ratio_at_treat_peak,
        "peak_ratio": treat_peak / base_peak,
        "max_pointwise_ratio": best_ratio,
        "max_pointwise_x": best_x,
    }


def write_tex(path, prefix, stats, group_name, x_name, base_label,
              treat_label, source=None):
    """Write one \newcommand per reported number.

    Ratios are emitted bare (e.g. 2.91) so the paper controls the formatting,
    as in `\SpeedupRepairBest$\times$`. Throughputs are emitted as bare
    integers, ready for siunitx's \num{}.
    """
    rated = {k: v for k, v in stats.items()
             if v["ratio_at_treat_peak"] is not None}
    if not rated:
        return None

    best = max(rated, key=lambda k: rated[k]["ratio_at_treat_peak"])
    b = rated[best]
    best_pw = max(stats, key=lambda k: stats[k]["max_pointwise_ratio"])
    p = stats[best_pw]

    lines = [
        "% Generated by speedup.py -- do not edit by hand.",
        f"% {treat_label} over {base_label}, by {group_name}.",
        f"% Regenerate with the plotting script that produced {os.path.basename(path)}.",
    ]
    if source:
        lines.append(f"% Source data: {source}")
    lines.append(f"% Generated: {datetime.date.today().isoformat()}")
    lines.append("")

    def cmd(name, value):
        lines.append(f"\\newcommand{{\\{prefix}{name}}}{{{value}}}")

    # Headline: ratio at x*, the treatment's peak-throughput concurrency, with
    # both modes measured at that same x*.
    lines.append(f"% Headline: measured at x* = the {x_name} where "
                 f"{treat_label} peaks.")
    cmd("Best", f"{b['ratio_at_treat_peak']:.1f}")
    cmd("BestGroup", best)
    cmd("BestX", b["treat_peak_x"])
    cmd("BestBaselineAtX", f"{b['base_at_treat_peak']:.0f}")
    cmd("BestTreatmentAtX", f"{b['treat_peak']:.0f}")
    lines.append("")

    # Context only: these compare the modes at DIFFERENT x, so do not mix them
    # with the headline in the same sentence.
    lines.append("% For reference only -- see speedup.py for what these mean.")
    cmd("BestIndependentPeaks", f"{b['peak_ratio']:.1f}")
    cmd("BestBaselinePeak", f"{b['base_peak']:.0f}")
    cmd("BestBaselinePeakX", b["base_peak_x"])
    cmd("BestMaxPointwise", f"{p['max_pointwise_ratio']:.1f}")
    cmd("BestMaxPointwiseGroup", best_pw)
    cmd("BestMaxPointwiseX", p["max_pointwise_x"])
    lines.append("")

    # Per-group numbers, for tables or a sentence about a specific config.
    # Each is measured at that group's own x*.
    lines.append(f"% Per-{group_name} speedups, each at its own x*.")
    for label in sorted(rated):
        s_ = rated[label]
        tag = tex_name(label)
        cmd(tag, f"{s_['ratio_at_treat_peak']:.1f}")
        cmd(f"{tag}X", s_["treat_peak_x"])
        cmd(f"{tag}BaselineAtX", f"{s_['base_at_treat_peak']:.0f}")
        cmd(f"{tag}TreatmentAtX", f"{s_['treat_peak']:.0f}")

    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


def report(groups, base_label, treat_label, x_name, group_name,
           metric="Throughput", out=None, tex=None, tex_prefix=None,
           source=None):
    """Print a speedup table, one row per group, plus the headline maximum.

    `groups` maps a group label (read ratio, account count, ...) to a
    (base_xy, treat_xy) pair. Returns the per-group stats keyed by group label.
    """
    lines = []
    stats = {}
    title = f"{metric} speedup: {treat_label} over {base_label}"
    lines.append("")
    lines.append("=" * len(title))
    lines.append(title)
    lines.append("=" * len(title))
    lines.append(
        f"  Headline ratio is measured at x* = the {x_name} where "
        f"{treat_label} peaks;")
    lines.append(
        f"  both modes are read off that same {x_name}.")
    lines.append("")
    lines.append(
        f"{group_name:>12} {'x*':>6} {base_label + ' @ x*':>22} "
        f"{treat_label + ' @ x*':>24} {'RATIO @ x*':>12} "
        f"{'(indep. peaks)':>15} {'(max pointwise)':>17}")

    for label in sorted(groups):
        base_xy, treat_xy = groups[label]
        s = compare(base_xy, treat_xy)
        if s is None:
            lines.append(f"{label:>14} {'(no data)':>22}")
            continue
        stats[label] = s
        if s["ratio_at_treat_peak"] is None:
            lines.append(
                f"{label:>12} {s['treat_peak_x']:>6} "
                f"{'(baseline not measured here)':>22}")
            continue
        lines.append(
            f"{label:>12} {s['treat_peak_x']:>6} "
            f"{s['base_at_treat_peak']:>22,.0f} "
            f"{s['treat_peak']:>24,.0f} "
            f"{s['ratio_at_treat_peak']:>11.1f}x "
            f"{s['peak_ratio']:>14.1f}x "
            f"{s['max_pointwise_ratio']:>16.1f}x")

    rated = {k: v for k, v in stats.items()
             if v["ratio_at_treat_peak"] is not None}
    if rated:
        best = max(rated, key=lambda k: rated[k]["ratio_at_treat_peak"])
        b = rated[best]
        lines.append("")
        lines.append(
            f"  HEADLINE: {b['ratio_at_treat_peak']:.1f}x at {group_name}={best}, "
            f"{x_name}={b['treat_peak_x']} "
            f"({b['treat_peak']:,.0f} vs {b['base_at_treat_peak']:,.0f} txns/sec, "
            f"both at {x_name}={b['treat_peak_x']})")
        best_pw = max(stats, key=lambda k: stats[k]["max_pointwise_ratio"])
        p = stats[best_pw]
        lines.append(
            f"  For reference only -- max pointwise: {p['max_pointwise_ratio']:.1f}x at "
            f"{group_name}={best_pw}, {x_name}={p['max_pointwise_x']}")
    else:
        lines.append("  (no comparable data for both modes)")
    lines.append("")

    text = "\n".join(lines)
    print(text)
    if out:
        with open(out, "w") as f:
            f.write(text + "\n")
        print(f"Speedup summary written to {out}")
    if tex and tex_prefix:
        written = write_tex(tex, tex_prefix, stats, group_name, x_name,
                            base_label, treat_label, source=source)
        if written:
            print(f"LaTeX macros written to {written}")
    return stats
